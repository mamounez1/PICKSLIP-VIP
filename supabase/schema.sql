-- PickSlip Database Schema for Supabase (PostgreSQL with RLS)

-- Enable UUID extension
create extension if not exists "uuid-ossp";

-- 1. Table: subscribers
create table if not exists public.subscribers (
    id bigint generated by default as identity primary key,
    user_id uuid references auth.users(id) on delete set null,
    email text unique not null,
    stripe_customer_id text,
    stripe_subscription_id text,
    subscription_status text not null default 'free' check (subscription_status in ('free', 'active', 'canceled', 'past_due')),
    current_period_end timestamptz,
    created_at timestamptz not null default now()
);

-- 2. Table: fixtures
create table if not exists public.fixtures (
    id bigint primary key, -- matches API-Football fixture id
    league text not null,
    home_team text not null,
    away_team text not null,
    kickoff timestamptz not null,
    home_team_id bigint not null,
    away_team_id bigint not null,
    status text not null default 'scheduled' check (status in ('scheduled', 'finished', 'in_play', 'canceled', 'postponed')),
    home_score integer,
    away_score integer,
    created_at timestamptz not null default now()
);

-- 3. Table: predictions
create table if not exists public.predictions (
    id uuid primary key default uuid_generate_v4(),
    fixture_id bigint not null references public.fixtures(id) on delete cascade,
    pick text not null,
    pick_type text not null,
    confidence numeric(5, 2) not null check (confidence >= 0 and confidence <= 100),
    reasoning text not null,
    is_free_pick boolean not null default false,
    result text not null default 'pending' check (result in ('pending', 'win', 'loss', 'void')),
    odds_est numeric(5, 2) default 1.85,
    created_at timestamptz not null default now()
);

-- 4. Table: stats_daily
create table if not exists public.stats_daily (
    date date primary key default current_date,
    picks_count integer not null default 0,
    wins integer not null default 0,
    losses integer not null default 0,
    win_rate numeric(5, 2) not null default 0.0
);

-- Enable Row Level Security (RLS) on all tables
alter table public.subscribers enable row level security;
alter table public.fixtures enable row level security;
alter table public.predictions enable row level security;
alter table public.stats_daily enable row level security;

-- RLS Policies:
-- Fixtures: Public read access
create policy "Public read access on fixtures"
    on public.fixtures for select
    using (true);

-- Predictions: Public read access (Free picks and VIP slips metadata)
create policy "Public read access on predictions"
    on public.predictions for select
    using (true);

-- Daily Stats: Public read access for transparent track record
create policy "Public read access on stats_daily"
    on public.stats_daily for select
    using (true);

-- Subscribers: Users can read their own subscriber record
create policy "Users can read own subscriber status"
    on public.subscribers for select
    using (auth.uid() = user_id or email = auth.jwt()->>'email');

-- Server-side / Service Role only for writes
create policy "Service role write access on fixtures"
    on public.fixtures for all
    using (auth.jwt()->>'role' = 'service_role');

create policy "Service role write access on predictions"
    on public.predictions for all
    using (auth.jwt()->>'role' = 'service_role');

create policy "Service role write access on stats_daily"
    on public.stats_daily for all
    using (auth.jwt()->>'role' = 'service_role');

create policy "Service role write access on subscribers"
    on public.subscribers for all
    using (auth.jwt()->>'role' = 'service_role');
